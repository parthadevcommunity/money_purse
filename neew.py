# THE REBUILT WORKER NODE USING YT-DLP EXCLUSIVELY
# =====================================================================
def process_single_video(video, output_folder):
    video_id = video["id"]
    title = video["title"]
    url = video["url"]

    # Jitter Anti-Ban Defense
    time.sleep(random.uniform(4.0, 8.0))

    # Configure options to pull ONLY the auto-generated or manual subtitles to disk
    temp_prefix = f"temp_{video_id}"
    ydl_opts = {
        "skip_download": True,
        "writeautomaticsub": True,  # Fallback to auto-captions
        "writesubtitles": True,  # Pull explicit manual tracks
        "subtitleslangs": ["te"],  # Lock strictly onto Telugu track profiles
        "outtmpl": f"{temp_prefix}.%(ext)s",
        "quiet": True,
        "no_warnings": True,
    }

    if os.path.exists(COOKIE_FILE):
        ydl_opts["cookiefile"] = COOKIE_FILE

    try:
        print(f"    [*] Fetching raw subtitles via yt-dlp: {video_id}")
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            ydl.download([url])

        # Search for the temporary subtitle file saved by yt-dlp onto your drive
        sub_files = glob.glob(f"{temp_prefix}.te.*")

        if not sub_files:
            log_video_status(video_id, title, url, "Skipped - Subtitles Missing")
            print(f"[-] Subtitles completely unavailable on server for [{title[:25]}]")
            return

        # Load the raw text file from local drive
        target_sub_file = sub_files
        with open(target_sub_file, "r", encoding="utf-8") as f:
            vtt_data = f.read()

        # Clean VTT string blocks down into standard speech text strings
        clean_telugu_text = clean_vtt_subtitles(vtt_data)

        # Cleanup: Instantly delete the temporary subtitle tracker file from your folder
        os.remove(target_sub_file)

        if not clean_telugu_text.strip():
            log_video_status(video_id, title, url, "Skipped - Empty Content")
            return

        # Translate clean string paragraph blocks over to English text chunks
        translator = GoogleTranslator(source="te", target="en")
        full_english_transcript = []

        # Split massive blocks into smaller array units to prevent translation timeout limits
        text_words = clean_telugu_text.split()
        chunk_size = 250  # Roughly 1,500 characters
        chunks = [
            " ".join(text_words[i : i + chunk_size])
            for i in range(0, len(text_words), chunk_size)
        ]

        print(f"    [*] Translating text chunks for video: {video_id}...")
        for idx, chunk in enumerate(chunks):
            translated_text = translator.translate(chunk.strip())
            full_english_transcript.append(
                f"[Segment {idx+1}] {translated_text}"
            )

        # Enforce file system character checks
        clean_title = re.sub(r'[\\/*?:"<>|]', "", title)
        filename = f"{output_folder}/{video_id}_{clean_title[:30].strip()}.md"

        with open(filename, "w", encoding="utf-8") as f:
            f.write(f"# {title}\nSource: {url}\n\n## Transcript\n")
            f.write("\n\n".join(full_english_transcript))

        log_video_status(video_id, title, url, "Success")
        print(f"[+] Successfully saved English Markdown file for: {title[:25]}")

    except Exception as e:
        error_msg = f"Failed Error: {str(e)[:50]}"
        log_video_status(video_id, title, url, error_msg)
        print(f"[!] Critical Error for video {video_id}: {error_msg}")

        # Emergency local file clean routines
        for f in glob.glob(f"{temp_prefix}.te.*"):
            try:
                os.remove(f)
            except:
                pass


def orchestrate_parallel_pipeline(
    playlist_url, output_folder="llm_knowledge_base", workers=2
):
    initialize_system_database()

    if not os.path.exists(output_folder):
        os.makedirs(output_folder)

    all_videos = get_all_playlist_entries(playlist_url)
    processed_ids = get_already_processed_ids()

    new_videos = [v for v in all_videos if v["id"] not in processed_ids]

    print(
        f"\n[📊 Status] Total Playlist Videos: {len(all_videos)} | Finished: {len(processed_ids)} | Unprocessed: {len(new_videos)}"
    )

    if not new_videos:
        print("[🎉] System clean. No new uploads discovered.")
        return

    print(f"[*] Starting thread pool with {workers} parallel channels...\n")
    with concurrent.futures.ThreadPoolExecutor(
        max_workers=workers
    ) as executor:
        futures = {
            executor.submit(process_single_video, video, output_folder): video
            for video in new_videos
        }
        concurrent.futures.wait(futures)

    print("\n[✓] Ingestion sequence finalized successfully.")




import concurrent.futures
import glob
import os
import random
import re
import sqlite3
import threading
import time
from deep_translator import GoogleTranslator
import yt_dlp

thread_local = threading.local()
DB_FILE = "pipeline_history.db"
COOKIE_FILE = "youtube_cookies.txt"


def get_db_connection():
    if not hasattr(thread_local, "connection"):
        thread_local.connection = sqlite3.connect(DB_FILE)
        thread_local.connection.execute("PRAGMA journal_mode=WAL;")
    return thread_local.connection


def initialize_system_database():
    conn = sqlite3.connect(DB_FILE)
    cursor = conn.cursor()
    cursor.execute(
        """
        CREATE TABLE IF NOT EXISTS video_history (
            video_id TEXT PRIMARY KEY,
            title TEXT,
            url TEXT,
            status TEXT,
            processed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """
    )
    conn.commit()
    conn.close()


def get_already_processed_ids():
    conn = sqlite3.connect(DB_FILE)
    cursor = conn.cursor()
    cursor.execute(
        "SELECT video_id FROM video_history WHERE status = 'Success'"
    )
    rows = cursor.fetchall()
    conn.close()
    return {row for row in rows}


def log_video_status(video_id, title, url, status):
    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute(
        """
        INSERT OR REPLACE INTO video_history (video_id, title, url, status)
        VALUES (?, ?, ?, ?)
    """,
        (video_id, title, url, status),
    )
    conn.commit()


def get_all_playlist_entries(playlist_url):
    print(f"[*] Fetching full structural layout for playlist: {playlist_url}")
    ydl_opts = {
        "extract_flat": "in_playlist",
        "skip_download": True,
        "quiet": True,
    }
    if os.path.exists(COOKIE_FILE):
        ydl_opts["cookiefile"] = COOKIE_FILE
        print("[+] Cookies attached to meta extraction pipeline.")

    with yt_dlp.YoutubeDL(ydl_opts) as ydl:
        try:
            result = ydl.extract_info(playlist_url, download=False)
            if "entries" in result:
                return [
                    {
                        "id": e.get("id"),
                        "title": e.get("title"),
                        "url": f"https://www.youtube.com/watch?v={e.get('id')}",
                    }
                    for e in result["entries"]
                    if e
                ]
        except Exception as e:
            print(f"[-] Meta extraction failed: {e}")
    return []


def clean_vtt_subtitles(vtt_content):
    """Parses raw VTT string content and drops timestamp tracks and format boilerplate."""
    lines = vtt_content.split("\n")
    cleaned_lines = []
    seen = set()

    for line in lines:
        line = line.strip()
        # Remove VTT headers and timing timeline tracking pointers
        if (
            not line
            or "-->" in line
            or line.startswith("WEBVTT")
            or line.startswith("Kind:")
            or line.startswith("Language:")
        ):
            continue

        # Strip standard HTML tags embedded inside automatic captions
        line = re.sub(r"<[^>]*>", "", line)

        # De-duplicate sequential text artifacts generated by scrolling transcripts
        if line not in seen:
            cleaned_lines.append(line)
            seen.add(line)

    return " ".join(cleaned_lines)


